package free.rm.skytube.gui.businessobjects;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.services.youtube.ItagItem;
import org.schabi.newpipe.extractor.stream.AudioStream;
import org.schabi.newpipe.extractor.stream.StreamInfo;
import org.schabi.newpipe.extractor.stream.StreamType;

import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Set;

class TrackSelectionManagerTest {
    private static final String GERMAN = "de";
    private static final String ENGLISH = "en";

    @Test
    void preferredQualityIsReusedForAnotherLanguage() {
        List<TrackSelectionManager.AudioTrackInfo> tracks = audioTracks();

        int index = TrackSelectionManager.findBestAudioTrackIndex(tracks, GERMAN, 128000);

        Assertions.assertEquals(2, index, "The exact quality of the requested language should win");
    }

    @Test
    void languageChangeFallsBackToSlightlyWorseQuality() {
        List<TrackSelectionManager.AudioTrackInfo> tracks = audioTracks();

        int index = TrackSelectionManager.findBestAudioTrackIndex(tracks, GERMAN, 192000);

        Assertions.assertEquals(2, index, "128 kbps is the best German track not above 192 kbps");
    }

    @Test
    void languageChangeFallsBackToLowestQualityWhenTargetIsTooLow() {
        List<TrackSelectionManager.AudioTrackInfo> tracks = audioTracks();

        int index = TrackSelectionManager.findBestAudioTrackIndex(tracks, GERMAN, 32000);

        Assertions.assertEquals(3, index, "The language should still switch when no matching quality exists");
    }

    @Test
    void missingQualityPreferencePicksHighestQuality() {
        List<TrackSelectionManager.AudioTrackInfo> tracks = audioTracks();

        int index = TrackSelectionManager.findBestAudioTrackIndex(tracks, GERMAN, 0);

        Assertions.assertEquals(1, index);
    }

    @Test
    void unknownLanguagesAreTreatedAsTheSameLanguage() {
        List<TrackSelectionManager.AudioTrackInfo> tracks = Arrays.asList(
                new TrackSelectionManager.AudioTrackInfo(null, "Unknown", 96000),
                new TrackSelectionManager.AudioTrackInfo(GERMAN, "German", 128000));

        int index = TrackSelectionManager.findBestAudioTrackIndex(tracks, null, 96000);

        Assertions.assertEquals(0, index);
    }

    @Test
    void autoGeneratedAudioLanguagesAreFound() {
        StreamInfo streamInfo = new StreamInfo(0, "url", "originalUrl",
                StreamType.VIDEO_STREAM, "id", "name", -1);
        streamInfo.setAudioStreams(Arrays.asList(
                audioStream("german", Locale.GERMAN, true),
                audioStream("english", Locale.ENGLISH, false)));

        Set<String> translated = TrackSelectionManager.findAutoTranslatedAudioLanguages(streamInfo);

        Assertions.assertEquals(java.util.Collections.singleton(GERMAN), translated);
    }

    private static AudioStream audioStream(String id, Locale locale, boolean autoGenerated) {
        ItagItem itagItem = new ItagItem(140, ItagItem.ItagType.AUDIO, MediaFormat.M4A, 128);
        itagItem.setAudioLocale(locale);
        itagItem.setAutoGenerated(autoGenerated);
        return new AudioStream.Builder()
                .setId(id)
                .setContent("url/" + id, true)
                .setMediaFormat(MediaFormat.M4A)
                .setAverageBitrate(128000)
                .setAudioLocale(locale)
                .setItagItem(itagItem)
                .build();
    }

    private static List<TrackSelectionManager.AudioTrackInfo> audioTracks() {
        return Arrays.asList(
                new TrackSelectionManager.AudioTrackInfo(ENGLISH, "English", 256000),
                new TrackSelectionManager.AudioTrackInfo(GERMAN, "German", 256000),
                new TrackSelectionManager.AudioTrackInfo(GERMAN, "German", 128000),
                new TrackSelectionManager.AudioTrackInfo(GERMAN, "German", 64000));
    }
}
